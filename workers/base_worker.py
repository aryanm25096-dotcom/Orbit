"""
workers/base_worker.py — Orbit Worker Roles (Phase 4)
======================================================
PRD §3.2, §4.3, §4.4:
  "Implement 3 worker roles (backend, frontend, database) as functions that
   take a TaskContract, call Ollama (same model for all three per Stage A in
   Section 4.3), use the Phase 3 tool gateway to edit files, and return an
   artifact plus status."

Worker Roles:
  - BackendWorker  (role: "backend")  — core functions, modules, algorithms, tests
  - FrontendWorker (role: "frontend") — CLI interfaces, presentation, templates, views
  - DatabaseWorker (role: "database") — schemas, models, queries, migrations

Each worker:
  1. Operates inside contract.allowed_workspace via ToolGateway.
  2. Seeds its workspace with target repo files and upstream dependency artifacts.
  3. Reads relevant inputs via gateway.read_file().
  4. Calls Ollama with role-specific system prompt requesting JSON file changes.
  5. Applies file writes strictly through ToolGateway (enforcing PathEscapeError and MAX_TOOL_CALLS).
  6. Executes tests if present via gateway.run_tests().
  7. Updates TaskContract with status, result_summary, and evidence dict.
"""

