# ---------------------------------------------------------------------------
# Workspace Initialization Helper
# ---------------------------------------------------------------------------

def seed_workspace(
    workspace_root: Path,
    target_dir: Path | None = None,
    upstream_workspaces: list[Path] | None = None,
) -> None:
    """
    Seed an isolated worker workspace with the baseline target directory files
    and any artifacts generated by completed upstream dependencies.
    """
    workspace_root.mkdir(parents=True, exist_ok=True)

    # 1. Copy baseline target files (skipping VCS and cache dirs)
    if target_dir and target_dir.exists():
        for src in target_dir.rglob("*"):
            if src.is_dir():
                continue
            rel = src.relative_to(target_dir)
            # Skip hidden / vcs / caches
            parts = rel.parts
            if any(p.startswith(".") or p in ("__pycache__", "venv", ".venv") for p in parts):
                continue
            dest = workspace_root / rel
            if not dest.exists():
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dest)

    # 2. Overlay upstream dependency artifacts / files if provided
    if upstream_workspaces:
        for up_ws in upstream_workspaces:
            if not up_ws.exists():
                continue
            for src in up_ws.rglob("*"):
                if src.is_dir():
                    continue
                rel = src.relative_to(up_ws)
                parts = rel.parts
                if any(p.startswith(".") or p in ("__pycache__",) for p in parts):
                    continue
                dest = workspace_root / rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dest)


