_ROLE_MAP: dict[str, type[BaseWorker]] = {
    "backend": BackendWorker,
    "frontend": FrontendWorker,
    "database": DatabaseWorker,
}


def run_worker(
    contract: TaskContract,
    gateway: ToolGateway | None = None,
    model: str = "nemotron-3-ultra:cloud",
    base_url: str = "http://localhost:11434",
    target_dir: Path | None = None,
    upstream_workspaces: list[Path] | None = None,
    ollama_caller: Callable[..., tuple[str, int, int]] | None = None,
) -> TaskContract:
    """Synchronous worker execution function."""
    role_key = contract.role.value if hasattr(contract.role, "value") else str(contract.role)
    worker_cls = _ROLE_MAP.get(role_key.lower(), BackendWorker)
    worker = worker_cls(
        model=model,
        gateway=gateway,
        base_url=base_url,
        target_dir=target_dir,
        upstream_workspaces=upstream_workspaces,
        ollama_caller=ollama_caller,
    )
    return worker.execute(contract)


