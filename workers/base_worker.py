async def run_worker_async(
    contract: TaskContract,
    gateway: ToolGateway | None = None,
    model: str = "nemotron-3-ultra:cloud",
    base_url: str = "http://localhost:11434",
    target_dir: Path | None = None,
    upstream_workspaces: list[Path] | None = None,
    ollama_caller: Callable[..., tuple[str, int, int]] | None = None,
) -> TaskContract:
    """Asynchronous worker execution function (runs synchronous execute in threadpool)."""
    return await asyncio.to_thread(
        run_worker,
        contract=contract,
        gateway=gateway,
        model=model,
        base_url=base_url,
        target_dir=target_dir,
        upstream_workspaces=upstream_workspaces,
        ollama_caller=ollama_caller,
    )
